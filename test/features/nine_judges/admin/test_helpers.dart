  String stateBefore = 'alive',
  String stateAfter = 'alive',
  int? turnDecisionTimeMs,
  int? eyeCandidateCount,
  bool wasReverseAction = false,
}) => GameActionLog(
  actionIndex: actionIndex,
  turnNumber: turnNumber,
  actingPlayer: actingPlayer,
  faction: faction,
  actionType: actionType,
  targetPersonId: targetPersonId,
  targetRank: targetRank,
  visibleTargetAttributeAtTime: null,
  actualTargetAttribute: actualTargetAttribute,
  stateBefore: stateBefore,
  stateAfter: stateAfter,
  lifeShieldBefore: false,
  lifeShieldAfter: false,
  judgedBefore: false,
  judgedAfter: false,
  actorHandBefore: const {},
  actorHandAfter: const {},
  opponentHandBefore: const {},
  opponentHandAfter: const {},
  timestamp: DateTime(2026, 1, 1),
  turnDecisionTimeMs: turnDecisionTimeMs,
  eyeCandidateCount: eyeCandidateCount,
  wasReverseAction: wasReverseAction,
);
